"""Turn a trained tree into text: a readable outline, a portable node table
that the C++ program loads, and C++ source with the tree as nested ifs."""

from pathlib import Path

from tree import DecisionTreeClassifier


def export_text(tree: DecisionTreeClassifier, names: list[str]) -> str:
    """An indented outline of the tree, one line per test and per leaf."""
    lines: list[str] = []

    def walk(node: int, indent: str) -> None:
        if tree.feature_[node] < 0:
            counts = ", ".join(str(int(c)) for c in tree.counts_[node])
            label = tree.classes_[int(tree.counts_[node].argmax())]
            lines.append(f"{indent}|--- class {label} ({counts})")
            return
        name, t = names[tree.feature_[node]], tree.threshold_[node]
        lines.append(f"{indent}|--- {name} <= {t:.4g}")
        walk(int(tree.left_[node]), indent + "|   ")
        lines.append(f"{indent}|--- {name} >  {t:.4g}")
        walk(int(tree.right_[node]), indent + "|   ")

    walk(0, "")
    return "\n".join(lines) + "\n"


def save_tree(tree: DecisionTreeClassifier, path: Path) -> None:
    """One line per node: id feature threshold left right class (feature -1 = leaf)."""
    lines = [
        f"# decision tree: {len(tree.feature_)} nodes, {tree.n_features_in_} features",
        "# node feature threshold left right class",
    ]
    for i in range(len(tree.feature_)):
        label = int(tree.classes_[int(tree.counts_[i].argmax())])
        lines.append(
            f"{i} {tree.feature_[i]} {float(tree.threshold_[i])!r} "
            f"{tree.left_[i]} {tree.right_[i]} {label}"
        )
    path.parent.mkdir(exist_ok=True)
    path.write_text("\n".join(lines) + "\n", newline="\n")


def to_cpp(tree: DecisionTreeClassifier, names: list[str], function: str) -> str:
    """C++17 source for one function that walks the tree with nested ifs."""
    out = [
        "// Generated by export.py from the trained decision tree. Do not edit.",
        "#pragma once",
        "",
        "namespace generated {",
        "",
        f"// The predicted class for one row of {tree.n_features_in_} features.",
        f"inline int {function}(const double* x)",
        "{",
    ]

    def walk(node: int, indent: str) -> None:
        if tree.feature_[node] < 0:
            label = int(tree.classes_[int(tree.counts_[node].argmax())])
            out.append(f"{indent}return {label};")
            return
        f, t = int(tree.feature_[node]), float(tree.threshold_[node])
        out.append(f"{indent}if (x[{f}] <= {t!r}) {{  // {names[f]}")
        walk(int(tree.left_[node]), indent + "    ")
        out.append(f"{indent}}}")
        walk(int(tree.right_[node]), indent)

    walk(0, "    ")
    out += ["}", "", "}  // namespace generated", ""]
    return "\n".join(out)
